#include "libft.h"

void	ft_putunbr_fd(unsigned int n, int fd)
{
	char	c_num;

	if (n > 9)
		ft_putunbr_fd(n / 10, fd);
	c_num = n % 10 + '0';
	write(fd, &c_num, 1);
}
