#include "libft.h"

void	ft_putlnbr_fd(long n, int fd)
{
	char	c_num;

	if (n == -9223372036854775807 - 1)
	{
		write(fd, "–9223372036854775808", ft_strlen("–9223372036854775808"));
		return ;
	}
	if (n < 0)
	{
		write(fd, "-", 1);
		n *= -1;
	}
	if (n > 9)
		ft_putlnbr_fd(n / 10, fd);
	c_num = n % 10 + 48;
	write(fd, &c_num, 1);
}
